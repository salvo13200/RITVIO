"""Unauthenticated public YouTube Music catalog adapter. No audio is read here."""
import json
import re
import sys
from pathlib import Path
# Embedded Windows Python intentionally excludes the script directory from sys.path.
# Only add our bundled, absolute resource directory for the catalog's sibling module.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from ytmusicapi import YTMusic

def thumbnail(item):
    images = item.get('thumbnails') or []
    return images[-1].get('url') if images else None

def artists(item):
    return [{'id': a['id'], 'name': a['name']} for a in item.get('artists', []) if a.get('id') and a.get('name')]

def seconds(item):
    if item.get('duration_seconds'):
        return item['duration_seconds']
    duration = item.get('duration') or item.get('length')
    if isinstance(duration, str) and re.fullmatch(r'\d+(?::\d{2}){1,2}', duration):
        total = 0
        for part in duration.split(':'):
            total = total * 60 + int(part)
        return total
    return 0

def song(item, fallback_artists=None, album=None):
    people = artists(item) or fallback_artists or []
    return {'videoId': item.get('videoId'), 'title': item.get('title') or 'Brano YouTube Music',
            'artist': ', '.join(a['name'] for a in people) or 'YouTube Music', 'duration': seconds(item),
            'artists': people, 'album': album or (item.get('album') if isinstance(item.get('album'), dict) else None)}

def resource(item, kind, fallback_artists=None):
    name = (item.get('artist') or item.get('name')) if kind == 'artist' else (item.get('title') or item.get('name'))
    return {'id': item.get('browseId'), 'name': name,
            'kind': kind, 'artwork': thumbnail(item), 'artists': artists(item) or fallback_artists or [],
            'year': item.get('year'), 'releaseType': item.get('type')}

def search_candidates(client, query):
    # An optional relevance lookup must not discard usable song/album results.
    # A failed lookup leaves ranking to the IDs actually present in credits.
    try:
        raw = client.search(query, filter='artists', limit=21, ignore_spelling=True)
        return [resource(item, 'artist') for item in raw[:20]
                if item.get('resultType') == 'artist' and item.get('browseId') and (item.get('artist') or item.get('name'))]
    except Exception:
        return []

def search_snapshot(payload):
    query = payload.get('query')
    if not isinstance(query, str) or not 3 <= len(query.strip()) <= 200:
        raise ValueError('Invalid query')
    client = YTMusic(language='en')
    raw = client.search(query, filter='songs', limit=101)
    seen = set()
    items = []
    for item in raw[:101]:
        key = item.get('videoId')
        if item.get('resultType') != 'song' or item.get('isAvailable') is False or not isinstance(key, str) or not re.fullmatch(r'[A-Za-z0-9_-]{11}', key) or key in seen:
            continue
        seen.add(key)
        items.append(song(item))
    return {'items': items[:100], 'candidates': search_candidates(client, query), 'truncated': len(raw) >= 101}

def catalog(payload):
    operation = payload.get('operation', 'search')
    if operation in ['home-index', 'home-collection', 'situation-index', 'situation-playlists']:
        from home_catalog import home_catalog
        return home_catalog(payload, song, resource, thumbnail)
    if operation == 'search':
        return search(payload)
    if operation == 'search-snapshot':
        return search_snapshot(payload)
    if operation == 'radio':
        video_id = payload.get('videoId')
        if not isinstance(video_id, str) or not re.fullmatch(r'[A-Za-z0-9_-]{11}', video_id):
            raise ValueError('Invalid radio seed')
        raw = YTMusic(language='en').get_watch_playlist(videoId=video_id, radio=True, limit=51)
        # One bounded provider operation, with no continuations generated by us.
        items = [song(item) for item in (raw.get('tracks') or [])[:51]
                 if item.get('isAvailable') is not False and item.get('videoId')
                 and item.get('videoType') in [None, 'MUSIC_VIDEO_TYPE_ATV', 'MUSIC_VIDEO_TYPE_OMV']]
        return {'videoId': video_id, 'items': items}
    client = YTMusic(language='en')
    kind = payload.get('kind')
    if kind not in ['artist', 'album']:
        raise ValueError('Invalid kind')
    if operation == 'catalog-search':
        query = payload.get('query')
        if not isinstance(query, str) or not 3 <= len(query.strip()) <= 200:
            raise ValueError('Invalid query')
        raw = client.search(query, filter='artists' if kind == 'artist' else 'albums', limit=21 if kind == 'artist' else 101)
        found = [resource(item, kind) for item in raw if item.get('resultType') == kind and item.get('browseId')]
        if kind == 'artist':
            return {'items': found[:20], 'truncated': len(found) > 20}
        return {'items': found[:100], 'truncated': len(raw) >= 101 or len(found) > 20,
                'candidates': search_candidates(client, query)}
    identifier = payload.get('id')
    if not isinstance(identifier, str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,160}', identifier):
        raise ValueError('Invalid id')
    if kind == 'artist' and operation == 'artist-search':
        query = payload.get('query', '')
        search_kind = payload.get('searchKind')
        if not isinstance(query, str) or len(query) > 200 or search_kind not in ['track', 'album']:
            raise ValueError('Invalid artist search')
        raw_artist = client.get_artist(identifier)
        name = raw_artist.get('name')
        if not isinstance(name, str) or not name.strip():
            raise ValueError('Missing artist name')
        same_or_prefixed = query.strip().casefold() == name.casefold() or query.strip().casefold().startswith(name.casefold() + ' ')
        term = name if not query.strip() else query.strip() if same_or_prefixed else name + ' ' + query.strip()
        raw = client.search(term, filter='songs' if search_kind == 'track' else 'albums', limit=101, ignore_spelling=True)
        found = []
        seen = set()
        for item in raw[:101]:
            if not any(person.get('id') == identifier for person in item.get('artists', [])):
                continue
            if search_kind == 'track':
                key = item.get('videoId')
                if item.get('resultType') != 'song' or item.get('isAvailable') is False or not isinstance(key, str) or not re.fullmatch(r'[A-Za-z0-9_-]{11}', key):
                    continue
                value = song(item)
            else:
                key = item.get('browseId')
                if item.get('resultType') != 'album' or not key:
                    continue
                value = resource(item, 'album')
            if key not in seen:
                seen.add(key)
                found.append(value)
        return {'kind': search_kind, 'items': found[:100], 'truncated': len(raw) >= 101 or len(found) > 100}
    if kind == 'album' and operation == 'detail':
        raw = client.get_album(identifier)
        people = artists(raw)
        summary = resource(raw, 'album')
        summary['id'] = identifier
        entries = []
        for index, item in enumerate(raw.get('tracks', [])[:1000]):
            available = item.get('isAvailable') is not False and isinstance(item.get('videoId'), str) and re.fullmatch(r'[A-Za-z0-9_-]{11}', item['videoId'])
            entries.append({'number': index + 1, 'title': item.get('title') or 'Traccia non disponibile', 'duration': seconds(item),
                            'track': song(item, people, {'id': identifier, 'name': raw.get('title')}) if available else None})
        count = raw.get('trackCount')
        return {**summary, 'description': raw.get('description') or '', 'entries': entries, 'reportedCount': count,
                'incomplete': len(raw.get('tracks', [])) > 1000 or (isinstance(count, int) and count > len(entries))}
    if kind == 'artist' and operation in ['detail', 'releases']:
        raw = client.get_artist(identifier)
        person = {'id': identifier, 'name': raw.get('name') or 'Artista'}
        if operation == 'releases':
            section_name = payload.get('section')
            if section_name not in ['albums', 'singles']:
                raise ValueError('Invalid section')
            section = raw.get(section_name) or {}
            items = client.get_artist_albums(section['browseId'], section['params'], limit=101) if section.get('browseId') and section.get('params') else section.get('results', [])
            return {'items': [resource(item, 'album', [person]) for item in items[:100] if item.get('browseId')], 'truncated': len(items) > 100}
        albums = raw.get('albums') or {}
        singles = raw.get('singles') or {}
        return {'id': identifier, 'name': person['name'], 'kind': 'artist', 'artwork': thumbnail(raw), 'artists': [], 'year': None, 'releaseType': None,
                'description': raw.get('description') or '',
                'tracks': [song(item, [person]) for item in (raw.get('songs') or {}).get('results', [])[:100] if item.get('isAvailable') is not False and item.get('videoId')],
                'albums': [resource(item, 'album', [person]) for item in albums.get('results', [])[:100] if item.get('browseId')],
                'singles': [resource(item, 'album', [person]) for item in singles.get('results', [])[:100] if item.get('browseId')],
                'moreAlbums': bool(albums.get('browseId') and albums.get('params')),
                'moreSingles': bool(singles.get('browseId') and singles.get('params'))}
    raise ValueError('Invalid operation')

def search(payload):
    query = payload.get('query')
    offset = payload.get('offset', 0)
    if not isinstance(query, str) or not 3 <= len(query.strip()) <= 200:
        raise ValueError('Invalid query')
    if not isinstance(offset, int) or offset < 0 or offset > 80 or offset % 20:
        raise ValueError('Invalid offset')
    # Public songs only. No authentication files, cookies, Premium or paid API.
    # English service labels avoid upstream localization parser failures; UI remains Italian.
    results = YTMusic(language='en').search(query, filter='songs', limit=offset + 21)
    entries = []
    seen = set()
    for item in results:
        video_id = item.get('videoId', '')
        if item.get('resultType') != 'song' or item.get('isAvailable') is False:
            continue
        if not isinstance(video_id, str) or not re.fullmatch(r'[A-Za-z0-9_-]{11}', video_id) or video_id in seen:
            continue
        seen.add(video_id)
        entries.append({
            'videoId': video_id,
            'title': item.get('title') or 'Brano YouTube Music',
            'artist': ', '.join(a['name'] for a in item.get('artists', []) if a.get('name')) or 'YouTube Music',
            'duration': item.get('duration_seconds') or 0,
            'artists': [{'id': a['id'], 'name': a['name']} for a in item.get('artists', []) if a.get('id') and a.get('name')],
            'album': item.get('album') if isinstance(item.get('album'), dict) else None,
        })
    return {'items': entries[offset:offset+20], 'nextOffset': offset+20 if len(entries)>offset+20 and offset<80 else None}

if __name__ == '__main__':
    try:
        print(json.dumps(catalog(json.load(sys.stdin)), ensure_ascii=False))
    except Exception as error:
        # Keep upstream details in the child only; the server sanitizes this output.
        print(type(error).__name__ + ': ' + str(error), file=sys.stderr)
        sys.exit(1)
